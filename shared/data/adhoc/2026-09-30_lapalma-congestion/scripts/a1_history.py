import pandas as pd, numpy as np, json
pd.set_option("display.width", 250); pd.set_option("display.max_rows", 200)
FAM = ["LA_PALMA_XF1A","LA_PALMA_XF1B","LA_PAL_VCAVAZ1_1","HAINE__LA_PAL1_1"]
da = pd.concat([pd.read_parquet("../raw/da_constraints_2024_2026H1.parquet"), pd.read_parquet("../raw/da_constraints_2026Q3.parquet")])
print(da.DATETIME.head(2).tolist())
fam_like = da[da.CONSTRAINTNAME.astype(str).str.contains("LA_PAL")].groupby("CONSTRAINTNAME").agg(hrs=("PRICE","size"), sum=("PRICE","sum"), first=("date","min"), last=("date","max")).sort_values("sum", ascending=False)
print(fam_like.to_string())
da = da[da.CONSTRAINTNAME.isin(FAM)].copy()
da["he_end"] = pd.to_datetime(da.DATETIME)
dah = da.groupby(["CONSTRAINTNAME","he_end"]).PRICE.max().reset_index()
dah.to_parquet("../derived/da_family_hourly.parquet")
rt = pd.concat([pd.read_parquet("../raw/rt_lapalma_2024_2026H1.parquet"), pd.read_parquet("../raw/rt_lapalma_2026Q3.parquet")])
rt = rt[rt.CONSTRAINTNAME.isin(FAM)].copy(); rt["ts"] = pd.to_datetime(rt.DATETIME)
rt["he_end"] = rt.ts.dt.floor("h") + pd.Timedelta(hours=1)
rth = rt.groupby(["CONSTRAINTNAME","he_end"]).agg(rt_px=("PRICE","mean"), rt_n=("PRICE","size"), rt_max=("PRICE","max"), lim=("LIMITMW","median"), flow=("VALUEMW","median")).reset_index()
rth.to_parquet("../derived/rt_family_hourly.parquet")
dah["m"] = dah.he_end.dt.to_period("M"); rth["m"] = rth.he_end.dt.to_period("M")
t1 = dah.pivot_table(index="m", columns="CONSTRAINTNAME", values="PRICE", aggfunc=["count","sum"]).fillna(0).round(0)
t2 = rth.pivot_table(index="m", columns="CONSTRAINTNAME", values="rt_px", aggfunc=["count","sum"]).fillna(0).round(0)
print("\nDA monthly (bind hrs / sum $):\n", t1.to_string()); print("\nRT monthly (bind hrs / sum of hourly mean $):\n", t2.to_string())
print("\nRT limit/flow history XF1A/XF1B:"); print(rth[rth.CONSTRAINTNAME.str.startswith("LA_PALMA_XF")].groupby(["CONSTRAINTNAME","m"]).lim.median().to_string())
